export function resolveSpecsFromTitle(title: string, rawBrand: string): PhoneSpecs {
  const storageMatch = title.match(/\b(64|128|256|512|1024)\s*GB\b/i) ?? title.match(/\b1\s*TB\b/i);
  let storageGb: number | null = null;
  if (storageMatch) {
    storageGb = storageMatch[0].toLowerCase().includes('tb')
      ? 1024
      : Number(storageMatch[1]);
  }

  const ramMatch = title.match(/\b(4|6|8|12|16)\s*GB\s*(?:de\s*)?RAM(?!\s*Boost)\b/i);
  const explicitRam = ramMatch ? Number(ramMatch[1]) : null;

  const matched = MODEL_PRESETS.find((p) => p.pattern.test(title));

  const has5g = /\b5G\b/i.test(title) || (matched?.has5g ?? false);
  const hasNfc = /\bNFC\b/i.test(title) || (matched?.hasNfc ?? false);
  const isApple = matched?.os === 'iOS' || /\biphone\b/i.test(title);

  let technicalScore = matched?.baseTechnicalScore ?? 20;
  if (storageGb && storageGb >= 256) technicalScore += 2;
  if (storageGb && storageGb >= 512) technicalScore += 1;
  if (explicitRam && explicitRam >= 8) technicalScore += 1;
  if (has5g && !matched) technicalScore += 2;
  if (hasNfc && !matched) technicalScore += 1;
  technicalScore = Math.max(10, Math.min(35, technicalScore));

  return {
    canonicalModel: matched?.canonicalModel ?? simplifyModelName(title, rawBrand),
    storageGb,
    ramGb: explicitRam ?? matched?.defaultRamGb ?? null,
    has5g,
    hasNfc,
    screenSummary: matched?.screenSummary ?? '6,6"+ Tela Full HD+',
    batteryMah: matched?.batteryMah ?? (isApple ? 3400 : 5000),
    cameraSummary: matched?.cameraSummary ?? '50MP Principal',
    chipset: matched?.chipset ?? (isApple ? 'Apple Silicon' : 'Octa-Core'),
    os: matched?.os ?? (isApple ? 'iOS' : 'Android'),
    anatelNote: 'Loja nacional oficial sujeita às normas de homologação Anatel e garantia legal CDC.',
    baseTechnicalScore: technicalScore,
  };
}

function simplifyModelName(title: string, rawBrand: string): string {
  const cleaned = title
    .replace(/^(kit\s+)?smartphone\s+/i, '')
    .replace(/\b(preto|branco|azul|verde|violeta|cinza|prata|dourado|grafite|rosa|lilás|titanio|titânio)\b/gi, '')
    .replace(/\s+/g, ' ')
    .trim();
  const words = cleaned.split(' ').slice(0, 5).join(' ');
  return words.toLowerCase().includes(rawBrand.toLowerCase())
    ? words
    : `${rawBrand} ${words}`.trim();
}
